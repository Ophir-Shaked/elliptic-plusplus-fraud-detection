"""The historic predictions were produced from original monolithic v3.1 source
with seed=777, CPU, and fold 1 under --smoke. The frozen fixture lives in
reference/v3_1_synthetic_fold1.csv and is NOT regenerated by this script.

Usage:
    python verify_synthetic_migration.py
    python verify_synthetic_migration.py --ap-atol 0.02
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from types import SimpleNamespace

import numpy as np
import pandas as pd
import torch
from sklearn.metrics import average_precision_score

from elliptic_fraud.config import MODELS
from elliptic_fraud.data import make_synthetic
from elliptic_fraud.models import fit_predict
from elliptic_fraud.preprocessing import preprocess


# ---- Command-line orchestration with strict nonzero failures ----
# WHY: The exact behavior depends on the entry-point file.
# FUNCTION: main — Compare every candidate to the locked synthetic v3.1 regression fixture.
# WHY: Keep input validation, business logic, and output handling explicit for reproducibility.
def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ap-atol',type=float,default=0.02,
                        help='Allowed AP change across library/CPU environments')
    parser.add_argument('--output',default=None)
    args = parser.parse_args()
    # IF (args.ap_atol < 0): Use a prior, explicitly permitted selection/calibration criterion, not exposed diagnostic labels.
    if args.ap_atol < 0:
        parser.error('Tolerance must be nonnegative')

    # REFERENCE FIXTURE: Historical AP values are deliberately not packaged
    # in the code-only repository. Validate their presence BEFORE model fitting.
    fixture = Path(__file__).parent / "reference" / "v3_1_synthetic_fold1.csv"
    if not fixture.is_file():
        raise SystemExit(
            "Missing optional historical reference: " + str(fixture) + "\n"
            "This GitHub code-only release intentionally excludes reference data. "
            "Copy the frozen v3.1 fixture from the research archive to run "
            "the migration regression test. Use pytest or --smoke for "
            "self-contained code checks."
        )

    # Use the same deterministic artificial transaction generator as v3.1.
    # Force CPU and one thread for easier local reproducibility.
    torch.set_num_threads(1)
    data = make_synthetic(seed=777)
    X,_,_ = preprocess(data,10,np.arange(93))
    train = data.ix(1,10)
    stop = data.ix(11,12)
    evaluation = data.ix(13,15)
    flags=SimpleNamespace(smoke=True,quick=True,gpu=False)

    reference = pd.read_csv(Path(__file__).parent/'reference'/'v3_1_synthetic_fold1.csv')
    assert set(reference.model)==set(MODELS)
    baseline=reference.set_index('model')
    rows=[]

    # LOOP (MODELS): Process every item using the same fixed input/output contract.
    for model in MODELS:
        # IMPORTANT: Use the shared interface so tabular and neural models follow the same time protocol.
        _,scores,info=fit_predict(model,data,X,train,stop,evaluation,flags,42,{})
        observed = float(average_precision_score(data.y[evaluation],scores))
        expected = float(baseline.loc[model,'legacy_AP'])
        delta=abs(observed-expected)
        rows.append({'model':model,'legacy_v31_AP':expected,'modular_AP':observed,
                     'abs_difference':delta,'tolerance':args.ap_atol,
                     'passed':delta<=args.ap_atol,
                     'selected_iterations':int(info['iterations'])})

    result=pd.DataFrame(rows)
    path=Path(args.output) if args.output else Path('synthetic_migration_report.csv')
    # IMPORTANT: Persist a reviewer-readable table for independent analysis and validation.
    result.to_csv(path,index=False)
    print(result.to_string(index=False))
    print('PASS' if result.passed.all() else 'FAIL', '| saved:',path)
    # IF (not result.passed.all()): Handle this alternate branch explicitly so that the experiment remains deterministic and auditable.
    if not result.passed.all():
        raise SystemExit(1)


# IF (__name__=='__main__'): Select a specific model implementation without altering the common fit/predict contract.
if __name__=='__main__':
    main()
